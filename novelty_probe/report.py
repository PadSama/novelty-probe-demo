SCHEMA = "novelty-probe/manifest@1"
PRISMA_S = "Rethlefsen et al. 2021, PRISMA-S, doi:10.1186/s13643-020-01542-z"


def sha256_file(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def local_match(raw_files):
    """{来源: {"with_abstract", "conforming", "nonconforming_share"}}，只统计服务器端做布尔检索的来源。"""
    from .sources import REGISTRY
    out = {}
    for path in raw_files:
        data = load_json_lenient(path)
        meta = data["meta"]
        src = REGISTRY.get(meta.get("source_api"))
        if src is None or src.capabilities.get("boolean") != "api":
            continue
        try:
            include, exclude = Q.parse(meta["query_original"]).lists()
        except (KeyError, ValueError):
            continue
        ignore = [w for g in exclude for w in g]
        st = out.setdefault(meta["source_api"], {"with_abstract": 0, "conforming": 0})
        for r in data["records"]:
            if r.get("abstract"):
                st["with_abstract"] += 1
                st["conforming"] += query_match(include, Doc(r.get("title"), r["abstract"]), exclude, ignore)
    for st in out.values():
        n = st["with_abstract"]
        st["nonconforming_share"] = round((n - st["conforming"]) / n, 4) if n else None
    return out


def build_manifest(root, raw_files, merged_meta, outputs, candidates):
    """raw_files：本次合并读取的原始结果文件；outputs：已写出的产出文件；candidates：候选（合并记录）。"""
    searches = []
    for path in raw_files:
        m = load_json_lenient(path)["meta"]
        searches.append({
            "file": rel(path, root), "sha256": sha256_file(path), "source": m.get("source_api"), "query_id": m.get("query_id"),
            "purpose": m.get("purpose"), "query_original": m.get("query_original"), "query_sent": m.get("query_sent"),
            "year_from": m.get("year_from"), "retrieved_at": m.get("retrieved_at"), "http_mode": (m.get("http") or {}).get("mode"),
            "conversion": m.get("conversion"), "total_hits": m.get("total_hits"), "returned": m.get("returned"),
            "warnings": len(m.get("warnings") or []), "config_hash": m.get("config_hash"),
        })
    return {
        "schema": SCHEMA,
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "tool": {"novelty_probe": __version__, "python": platform.python_version(), "platform": sys.platform},
        "config": {"file": merged_meta.get("config_file"), "hash": merged_meta.get("config_hash")},
        "method": merged_meta.get("method"),
        "parameters": merged_meta.get("parameters"),
        "searches": searches,
        "outputs": [{"file": rel(p, root), "sha256": sha256_file(p)} for p in outputs],
        "counts": {**{k: merged_meta["counts"][k] for k in ("raw_records", "merged_records", "duplicates_removed", "dedupe",
                                                            "with_authors", "id_status") if k in merged_meta["counts"]},
                   "local_match": local_match(raw_files)},
        "candidates": {"top_k": (merged_meta.get("candidates") or {}).get("top_k"),
                       "sort": (merged_meta.get("candidates") or {}).get("sort"),
                       "items": [{"merged_id": x["merged_id"], "doi": x.get("doi"), "arxiv_id": x.get("arxiv_id"),
                                  "title": x.get("title")} for x in candidates]},
    }


def render_report(m, suffix=""):
    """清单 → Markdown 检索报告（当前界面语言）。"""
    run = suffix.lstrip("_") or "v1"
    searches = m["searches"]
    dates = sorted(s["retrieved_at"][:10] for s in searches if s.get("retrieved_at"))
    sources = list(dict.fromkeys(s["source"] for s in searches))
    out = [tr("# 检索报告：{run}", "# Search report: {run}", run=run), ""]
    out.append("> " + tr("由 merge.py 自动生成（{t}）；格式参照 {p}。数字取自 run_manifest{s}.json。",
                         "Generated by merge.py ({t}); format follows {p}. Figures come from run_manifest{s}.json.",
                         t=m["created_at"], p=PRISMA_S, s=suffix))
    out += ["", "## " + tr("数据库与接口", "Databases and interfaces"), "",
            "| " + tr("来源 | 接口 | 匹配字段 | 排序", "Source | Interface | Fields searched | Ranking") + " |", "|---|---|---|---|"]
    for name in sources:
        src = REGISTRY.get(name)               # 各数据源在适配器里写明自己的接口与排序（未登记的只写名字）
        label, iface, ranking = (src.label or name, src.interface, src.ranking) if src else (name, "", ("", ""))
        out.append(f"| {label} | `{iface}` | {tr('标题 + 摘要', 'title + abstract')} | {tr(*ranking)} |")
    out += ["", tr("检索日期：{d}。工具：novelty-probe {v}，Python {py}。配置指纹：{h}。",
                   "Search dates: {d}. Tool: novelty-probe {v}, Python {py}. Configuration fingerprint: {h}.",
                   d=(dates[0] + (" – " + dates[-1] if dates[-1] != dates[0] else "")) if dates else "-",
                   v=m["tool"]["novelty_probe"], py=m["tool"]["python"], h=(m.get("config") or {}).get("hash") or "-")]
    out += ["", "## " + tr("检索式", "Search strategies"), ""]
    by_query = {}
    for s in searches:
        by_query.setdefault(s["query_id"], []).append(s)
    for qid in sorted(by_query, key=qnum):
        rows = by_query[qid]
        first = rows[0]
        limit = tr("{y} 年起", "from {y}", y=first["year_from"]) if first.get("year_from") else tr("无", "none")
        out.append(tr("**{q}**（{p}；年份限制：{l}）", "**{q}** ({p}; year limit: {l})", q=qid, p=first.get("purpose") or "-", l=limit))
        out.append("")
        out.append("```text")
        out.append(first.get("query_original") or "")
        for s in rows:
            out.append(f"{s['source']}: {s.get('query_sent') or ''}")
        out.append("```")
        out.append("")
    out += ["## " + tr("结果数", "Results"), "",
            "| " + tr("检索式 | 来源 | 命中数 | 保存数", "Query | Source | Hits | Saved") + " |", "|---|---|---|---|"]
    for s in searches:
        out.append(f"| {s['query_id']} | {s['source']} | {s.get('total_hits') if s.get('total_hits') is not None else '-'} | "
                   f"{s.get('returned') if s.get('returned') is not None else '-'} |")
    c = m["counts"]
    d = c.get("dedupe") or {}
    merged_rules = {**(d.get("id_links") or {}), **(d.get("version_links") or {})}
    out += ["", "## " + tr("去重与候选", "Deduplication and candidates"), "",
            "- " + tr("原始记录 {r} 条，去重后 {m} 篇（去掉 {k} 条）。", "{r} raw records, {m} works after deduplication ({k} removed).",
                      r=c.get("raw_records"), m=c.get("merged_records"), k=c.get("duplicates_removed")),
            "- " + tr("合并依据（规则编号见 merged{s}.json 的 meta.dedupe_rules）：{x}。",
                      "Merge rules applied (see meta.dedupe_rules in merged{s}.json): {x}.", s=suffix,
                      x=", ".join(f"{k} × {v}" for k, v in merged_rules.items()) or "-"),
            "- " + tr("疑似重复但保持分开：{x}。", "Possible duplicates kept separate: {x}.",
                      x=", ".join(f"{k} × {v}" for k, v in (d.get("kept_separate") or {}).items()) or tr("无", "none")),
            "- " + tr("带作者的记录：{a} / {m} 篇。", "Works with authors: {a} of {m}.", a=c.get("with_authors", 0), m=c.get("merged_records")),
            "- " + (tr("候选：前 {k} 篇，按 RRF（k={r}）降序，同分按 BM25 降序，再按合并编号。",
                       "Candidates: top {k}, sorted by RRF (k={r}) descending, then BM25 descending, then merged_id.",
                       k=m["candidates"].get("top_k"), r=(m.get("parameters") or {}).get("rrf_k"))
                    if (m.get("parameters") or {}).get("rrf_k") is not None else
                    tr("候选：前 {k} 篇，排序：{s}。", "Candidates: top {k}, sorted by {s}.",
                       k=m["candidates"].get("top_k"), s=m["candidates"].get("sort") or "-"))]
    lm = c.get("local_match") or {}
    if lm:
        parts = [tr("{s} {p}%（{n} 条有摘要的记录中 {k} 条）", "{s} {p}% ({k} of {n} records with an abstract)",
                    s=s, p=round(100 * (v["nonconforming_share"] or 0), 1), n=v["with_abstract"],
                    k=v["with_abstract"] - v["conforming"]) for s, v in lm.items()]
        out += ["", "## " + tr("本地匹配的偏差", "Local matching bias"), "",
                tr("服务器已按标题与摘要做过布尔检索，返回的记录按定义满足检索式；其中被本地判为不满足的比例：{x}。"
                   "这是本地匹配（Porter 词干还原近似）漏判率的上限，影响 BM25、n_conform 与证据检查里的判断。",
                   "The servers already applied the Boolean query to titles and abstracts, so every record they return satisfies "
                   "it; the share that local matching judged non-conforming: {x}. This bounds the false-negative rate of local "
                   "matching (Porter stemming as an approximation), which feeds BM25, n_conform and the evidence check.",
                   x=t("verify.sep").join(parts))]
    credited = [REGISTRY[n] for n in sources if n in REGISTRY and REGISTRY[n].attribution[0]]
    if credited:
        out += ["", "## " + tr("数据来源与条款", "Data sources and terms"), ""]
        out += ["- " + tr(*src.attribution) for src in credited]
        out.append("- " + tr("摘要的版权属于出版方或作者；本报告不含摘要。",
                             "Abstracts remain the copyright of their publishers or authors; this report contains none."))
    out += ["", "## " + tr("文件", "Files"), ""]
    out.append("- " + tr("检索结果：{n} 个文件（哈希见 run_manifest{s}.json 的 searches）",
                         "Search results: {n} files (hashes under searches in run_manifest{s}.json)", n=len(searches), s=suffix))
    for o in m["outputs"]:
        out.append(f"- `{o['file']}`")
    return "\n".join(out) + "\n"


def _work_key(x):
    if x.get("doi"):
        return "doi:" + x["doi"].lower()
    if x.get("arxiv_id"):
        return "arxiv:" + x["arxiv_id"].lower()
    return "title:" + title_key(x.get("title"))


def diff(a, b):
    """比较两份清单：检索结果文件的增减与变化（命中数、保存数、哈希），候选的进出（按 DOI / arXiv ID / 题目）。"""
    sa = {s["file"]: s for s in a["searches"]}
    sb = {s["file"]: s for s in b["searches"]}
    changed = []
    for f in sorted(set(sa) & set(sb)):
        x, y = sa[f], sb[f]
        if x["sha256"] != y["sha256"]:
            changed.append({"file": f, "total_hits": [x.get("total_hits"), y.get("total_hits")],
                            "returned": [x.get("returned"), y.get("returned")],
                            "retrieved_at": [x.get("retrieved_at"), y.get("retrieved_at")]})
    ca = {_work_key(x): x for x in a["candidates"]["items"]}
    cb = {_work_key(x): x for x in b["candidates"]["items"]}
    return {
        "searches": {"added": sorted(set(sb) - set(sa)), "removed": sorted(set(sa) - set(sb)), "changed": changed},
        "candidates": {"added": [cb[k] for k in cb if k not in ca], "removed": [ca[k] for k in ca if k not in cb],
                       "kept": sum(1 for k in cb if k in ca)},
        "config": {"same": (a.get("config") or {}).get("hash") == (b.get("config") or {}).get("hash")},
    }
